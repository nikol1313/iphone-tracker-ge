const dictionaries = { en, ka };

export function t(key, vars = {}) {
  const entry = dictionaries[lang][key] ?? en[key];
  if (entry === undefined) return key;
  const text = typeof entry === "function" ? entry(vars) : entry;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

export function translateServerMessage(message) {
  if (lang === "en") return message;
  for (const [pattern, georgian] of serverMessages) {
    if (pattern.test(message)) return message.replace(pattern, georgian);
  }
  return message;
}

/* Fill [data-i18n] text, [data-i18n-html] trusted markup, and [data-i18n-attr="attr:key;…"]. */
export function translatePage(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll("[data-i18n]").forEach(element => { element.textContent = t(element.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach(element => { element.innerHTML = t(element.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-attr]").forEach(element => {
    element.dataset.i18nAttr.split(";").forEach(pair => {
      const [attribute, key] = pair.split(":");
      element.setAttribute(attribute, t(key));
    });
  });
}

export function switchLanguage() {
  lang = lang === "ka" ? "en" : "ka";
  locale = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // The switch still applies to this visit.
  }
  translatePage();
  languageListeners.forEach(render => render());
}
